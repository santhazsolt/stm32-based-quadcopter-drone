// Validate the frame checksum (matches your Arduino frameIsValid)
uint8_t ibus_frame_is_valid(void)
{
    uint16_t checksum = 0xFFFF;
    for (uint8_t i = 0; i < 30; i++)
        checksum -= ibus_buffer[i];

    uint16_t received = ibus_buffer[30] | (ibus_buffer[31] << 8);
    return (checksum == received);
}

// Decode all 14 channels (matches your Arduino decodeChannels)
void decode_ibus_channels(void)
{
    for (uint8_t ch = 0; ch < IBUS_CHANNELS; ch++)
    {
        ibus_channels.ch[ch] = ibus_buffer[2 + ch * 2] |
                               (ibus_buffer[3 + ch * 2] << 8);
    }
}

void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
    if (huart == &huart2)
    {
        uint8_t b = ibus_buffer[ibus_index];   // the byte just received

        // Same header logic as your Arduino readIbus()
        if (ibus_index == 0 && b != 0x20)
        {
            // not a start byte — keep waiting at index 0
            HAL_UART_Receive_IT(&huart2, (uint8_t *)&ibus_buffer[0], 1);
            return;
        }
        if (ibus_index == 1 && b != 0x40)
        {
            // bad second byte — reset to look for start again
            ibus_index = 0;
            HAL_UART_Receive_IT(&huart2, (uint8_t *)&ibus_buffer[0], 1);
            return;
        }

        ibus_index++;

        if (ibus_index == IBUS_FRAME_LEN)
        {
            ibus_index = 0;
            if (ibus_frame_is_valid())
                decode_ibus_channels();
        }

        // queue reception of the next byte into the next buffer slot
        HAL_UART_Receive_IT(&huart2, (uint8_t *)&ibus_buffer[ibus_index], 1);
    }
}

